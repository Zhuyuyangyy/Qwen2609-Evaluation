"""
export_synthetic_ab300
======================

Freeze the AffectiveBenchmark-300 task set into a stable JSON file.

The original benchmark generates tasks dynamically from code-embedded
templates via ``AffectiveBenchmark(seed=42, size=300)``. This script
captures that output once, adds provenance metadata, and writes it to
``data/rebuild/synthetic_ab300_seed42.json`` so the dataset becomes a
*inspectable, version-controlled data asset* rather than ephemeral code
output.

Naming
------
The dataset is renamed from "Semi-Real-300" to **Synthetic-AB300** to
reflect its true nature: 60 hand-written templates repeated ~5 times.
It is a mechanism sanity check, NOT real-world evidence.

Usage
-----
    python experiments/rebuild/export_synthetic_ab300.py --seed 42
    python experiments/rebuild/export_synthetic_ab300.py --seed 42 --size 100
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))

from emotion_agent.affective_benchmark import AffectiveBenchmark, TaskCategory


# Map risk levels to 4-level decisions (same logic as run_real_benchmark.gold_decision)
_RISK_TO_HEURISTIC_GOLD = {
    "CRITICAL": "HUMAN_REVIEW",
    "HIGH": "SIMULATE_FIRST",
    "MEDIUM": "SIMULATE_FIRST",
    "LOW": "AUTO_EXECUTE",
}


def _heuristic_gold_decision(task) -> str:
    """Derive a heuristic gold decision from task labels.

    This is NOT a human-validated label. It is a deterministic mapping
    from the hand-authored task metadata (ground_truth_action,
    expected_behavior, expected_risk_level).
    """
    gt = task.ground_truth_action.lower()
    beh = task.expected_behavior.lower()
    risk = task.expected_risk_level.upper()

    if gt == "block" or "block" in beh:
        return "BLOCK"
    if "human" in gt or "human" in beh or gt == "human_review_required":
        return "HUMAN_REVIEW"
    if gt in ("auto_execute",) or beh.startswith("auto execute"):
        return "AUTO_EXECUTE"
    if risk == "CRITICAL":
        return "HUMAN_REVIEW"
    return "SIMULATE_FIRST"


def _template_id(description: str, category: str) -> str:
    """Generate a stable template ID from description + category."""
    # Use a simple hash of the description for stability
    return f"tpl_{abs(hash(description + category)) % 10000:04d}"


def export_dataset(seed: int = 42, size: int = 300) -> dict:
    """Generate and export the Synthetic-AB300 dataset."""
    bench = AffectiveBenchmark(seed=seed, size=size)

    # Count unique descriptions to verify template repetition
    unique_descriptions = set()
    records = []
    for task in bench.tasks:
        unique_descriptions.add(task.description)
        records.append({
            "id": task.id,
            "category": task.category.value,
            "description": task.description,
            "expected_risk_level": task.expected_risk_level,
            "heuristic_gold_decision": _heuristic_gold_decision(task),
            "source_type": "synthetic_template",
            "template_id": _template_id(task.description, task.category.value),
            "seed": seed,
            "generation_note": (
                "Generated by AffectiveBenchmark from code-embedded templates. "
                "NOT human-validated. Gold labels are heuristic, not independent "
                "human annotation."
            ),
        })

    # Provenance metadata
    dataset = {
        "dataset_name": "Synthetic-AB300",
        "former_name": "Semi-Real-300 (deprecated, misleading)",
        "seed": seed,
        "size": size,
        "n_unique_templates": len(unique_descriptions),
        "n_total_records": len(records),
        "template_repetition_ratio": round(len(records) / max(1, len(unique_descriptions)), 2),
        "category_distribution": dict(Counter(r["category"] for r in records)),
        "risk_level_distribution": dict(Counter(r["expected_risk_level"] for r in records)),
        "gold_decision_distribution": dict(Counter(r["heuristic_gold_decision"] for r in records)),
        "provenance": {
            "generator": "emotion_agent.affective_benchmark.AffectiveBenchmark",
            "source_type": "synthetic_template",
            "human_validated": False,
            "independent_annotation": False,
            "cohen_kappa": None,
            "intended_use": "mechanism sanity check only",
            "not_intended_for": [
                "real-world safety validation",
                "external effectiveness claims",
                "human-validated benchmark comparison",
            ],
        },
        "records": records,
    }

    return dataset


def main():
    parser = argparse.ArgumentParser(
        description="Export Synthetic-AB300 dataset to JSON"
    )
    parser.add_argument("--seed", type=int, default=42, help="Random seed (default: 42)")
    parser.add_argument("--size", type=int, default=300, help="Dataset size (default: 300)")
    args = parser.parse_args()

    dataset = export_dataset(seed=args.seed, size=args.size)

    # Write to data/rebuild/
    out_dir = os.path.join(os.path.dirname(__file__), "..", "..", "data", "rebuild")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, f"synthetic_ab300_seed{args.seed}.json")

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(dataset, f, indent=2, ensure_ascii=False)

    print(f"Exported {dataset['n_total_records']} records "
          f"({dataset['n_unique_templates']} unique templates) "
          f"to {out_path}")
    print(f"Category distribution: {dataset['category_distribution']}")
    print(f"Risk level distribution: {dataset['risk_level_distribution']}")
    print(f"Gold decision distribution: {dataset['gold_decision_distribution']}")


if __name__ == "__main__":
    main()
